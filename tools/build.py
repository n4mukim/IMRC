#!/usr/bin/env python3
"""Build the IMRC static site: python3 tools/build.py  ->  writes HTML into ../site/"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from common import *
import pages_main, pages_en, blog_static, security_headers

count = 0
for lg in LANGS:
    state["lang"] = lg
    for fn in pages_main.MAIN_PAGES:
        path, html = fn()
        write(out_path(path, lg), html)
        count += 1
state["lang"] = "en"
for fn in pages_en.EN_PAGES:
    path, html = fn()
    rel = "404.html" if path.endswith(".html") else out_path(path, "en")
    write(rel, html)
    count += 1

# blog posts: one static page per PUBLISHED post, the RSS feed, and (below) sitemap entries
posts = blog_static.load_posts()
count += blog_static.write_all(posts, write)

# 301 redirects for the removed Research & Articles section (and any imported legacy article URLs)
import json
redirects = ["/research /blog/ 301", "/research/ /blog/ 301", "/research/* /blog/ 301", "/articles /blog/ 301", "/articles/ /blog/ 301", "/articles/* /blog/ 301"]
legacy_file = Path(__file__).parent / "legacy_articles.json"       # [{"old": "/research/old-article", "slug": "new-slug"}]
legacy = json.loads(legacy_file.read_text(encoding="utf8")) if legacy_file.exists() else []
specific = [f"{x['old']} /blog/{x['slug']}/ 301" for x in legacy]
write("_redirects", "\n".join(specific + redirects) + "\n")
write("vercel.json", json.dumps({"redirects": [{"source": x["old"], "destination": f"/blog/{x['slug']}/", "permanent": True} for x in legacy] + [
    {"source": "/research/:path*", "destination": "/blog/", "permanent": True},
    {"source": "/articles/:path*", "destination": "/blog/", "permanent": True}],
    "headers": security_headers.vercel_headers()}, indent=2) + "\n")
write("_headers", security_headers.headers_file())
write("research/index.html", '<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Moved to the blog · IMRC</title><meta http-equiv="refresh" content="0; url=/blog/"><link rel="canonical" href="' + BASE_URL + '/blog/"><meta name="robots" content="noindex"></head><body><p>This page moved. <a href="/blog/">Go to the IMRC blog</a>.</p></body></html>\n')

# sitemap (one per language would be generated by the CMS; this static one lists every URL)
urls = []
for lg in LANGS:
    for fn in pages_main.MAIN_PAGES:
        state["lang"] = lg
        urls.append(BASE_URL + u(fn()[0], lg))
state["lang"] = "en"
for fn in pages_en.EN_PAGES:
    p = fn()[0]
    if not p.endswith(".html") and p not in ("/blog/post/", "/blog/write/", "/blog/dashboard/", "/blog/join/", "/blog/review/"):   # private/app pages are noindex
        urls.append(BASE_URL + p)
write("sitemap.xml", '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join([f"<url><loc>{x}</loc></url>" for x in urls] + blog_static.sitemap_entries(posts)) + "\n</urlset>\n")
write("robots.txt", f"User-agent: *\nAllow: /\nSitemap: {BASE_URL}/sitemap.xml\n")
print(f"built {count} pages")
